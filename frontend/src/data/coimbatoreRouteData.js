/**
 * Helper to retrieve the ordered stops for a specific bus.
 * Falls back to Bus 12 route if the specific bus ID is not found.
 */
export const getBusRoute = (busId) => {
  if (!busId) return SEEDED_COIMBATORE_STOPS;
  const normalizedId = String(busId).toUpperCase().trim();
  if (BUS_ROUTES[normalizedId]) return BUS_ROUTES[normalizedId];

  const numMatch = normalizedId.match(/\d+/);
  if (numMatch) {
    const num = parseInt(numMatch[0], 10);
    const paddedKey = `BUS-${num < 10 ? '0' + num : num}`;
    const unpaddedKey = `BUS-${num}`;
    if (BUS_ROUTES[paddedKey]) return BUS_ROUTES[paddedKey];
    if (BUS_ROUTES[unpaddedKey]) return BUS_ROUTES[unpaddedKey];
  }

  return SEEDED_COIMBATORE_STOPS;
};
